function runs(text, base = {}) {
  const out = [];
  for (const seg of String(text).split(/(\*\*[^*]+\*\*|\{[官部社推測]\})/)) {
    if (!seg) continue;
    const m = seg.match(/^\{([官部社推測])\}$/);
    if (m) { const [n, c] = TAGS[m[1]]; out.push(new TextRun({ text: `〔${n}〕`, font: FONT, size: (base.size || 21) - 3, color: c, bold: true })); continue; }
    if (seg.startsWith('**')) { out.push(new TextRun({ text: seg.slice(2, -2), font: FONT, bold: true, size: base.size || 21, color: base.color })); continue; }
    out.push(new TextRun({ text: seg, font: FONT, size: base.size || 21, color: base.color, bold: base.bold }));
  }
  return out;
}
